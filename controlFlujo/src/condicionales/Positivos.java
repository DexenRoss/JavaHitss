package condicionales;

public class Positivos {
    public static void main(String[] args) {
        int num = 23;
        if (num >=0){
            System.out.println(num+" Es Positivo");
        } else if (num <=0){
            System.out.println(num+" Es Negativo");
        } else {
            System.out.println("ES 0");
        }
    }
}
