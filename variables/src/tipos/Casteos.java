package tipos;

public class Casteos {
    public static void main(String[] args) {
        int i = 30000;
        System.out.println("i: "+i);
        double d = (double) i;
        System.out.println("d: "+d);
        // Nose puede castear de un tipo primitivo a String

        Integer valor = 34;
        System.out.println(valor.toString());
    }
    
} 
    
