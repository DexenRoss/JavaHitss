package classes;

public class Calculator {
    public int suma(int a, int b){
        return a+b;
    }

    public double suma(double a, int b){
        return a+b;
    }

    public long suma(long a, long b){
        return a+b;
    }

    public int suma(int a, int b, int c){
        return a+b+c;
    }
}
